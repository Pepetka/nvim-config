test("order functions and metadata sorts are one-time and tab-local", function()
  plugin.setup()
  local z, a, m = file("z.lua"), file("a.lua"), file("m.lua")
  show(z)
  show(a)
  show(m)
  equal(plugin.move(-1), true)
  equal(plugin.buffers(), { z, m, a })
  equal(plugin.move_to(1), true)
  equal(plugin.buffers(), { m, z, a })
  equal(plugin.sort("name"), true)
  equal(plugin.buffers(), { a, m, z })
  equal(plugin.sort("path"), true)
  equal(plugin.buffers(), { z, a, m })
  equal(plugin.sort("id"), false)
  equal(plugin.reorder({ m, a, z }), true)
  equal(
    plugin.sort(function(x, y)
      return x < y
    end),
    true
  )
  local new = file("0.lua")
  plugin.add(new)
  equal(plugin.buffers(), { z, a, m, new })
  local before = plugin.buffers()
  raises(function()
    plugin.sort(function()
      error("bad comparator")
    end)
  end, "bad comparator")
  equal(plugin.buffers(), before)
end)

