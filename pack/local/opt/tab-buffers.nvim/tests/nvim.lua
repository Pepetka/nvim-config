test("working functions require setup; teardown is idempotent", function()
  raises(function()
    plugin.buffers()
  end, "setup")
  raises(function()
    plugin.refresh()
  end, "setup")
  raises(function()
    plugin.next()
  end, "setup")
  equal(plugin.teardown(), false)
  equal(plugin.setup(), true)
  equal(plugin.teardown(), true)
  equal(plugin.teardown(), false)
end)

