local tests, notices = {}, {}
local sequence = 0
local real_notify = vim.notify
vim.notify = function(message)
  notices[#notices + 1] = message
end
local saved = {
  nvim_win_set_buf = api.nvim_win_set_buf,
  nvim_buf_delete = api.nvim_buf_delete,
  nvim_open_win = api.nvim_open_win,
}

local function equal(actual, expected)
  assert(vim.deep_equal(actual, expected), "expected " .. vim.inspect(expected) .. ", got " .. vim.inspect(actual))
end

local function raises(fn, text)
  local ok, err = pcall(fn)
  assert(not ok, "expected an error")
  if text then
    assert(tostring(err):find(text, 1, true), tostring(err))
  end
end

local function drain()
  for _ = 1, 2 do
    local ready = false
    vim.schedule(function()
      ready = true
    end)
    assert(
      vim.wait(1000, function()
        return ready
      end, 1),
      "scheduled work did not finish"
    )
  end
end

local function file(name, lines)
  sequence = sequence + 1
  local buf = api.nvim_create_buf(true, false)
  api.nvim_buf_set_name(buf, "/private/tmp/tab-buffers-tests/" .. sequence .. "/" .. (name or "file.lua"))
  api.nvim_buf_set_lines(buf, 0, -1, false, lines or { "text" })
  vim.bo[buf].modified = false
  return buf
end

local function show(buf)
  api.nvim_set_current_buf(buf)
  drain()
end

local function reset()
  for name, fn in pairs(saved) do
    api[name] = fn
  end
  plugin.teardown()
  api.nvim_create_augroup("TabBuffersTests", { clear = true })
  vim.o.hidden, vim.o.confirm, vim.o.autowrite = true, false, false
  for _, buf in ipairs(api.nvim_list_bufs()) do
    if api.nvim_buf_is_valid(buf) then
      vim.bo[buf].modified = false
      vim.bo[buf].bufhidden = ""
    end
  end
  for _, win in ipairs(api.nvim_list_wins()) do
    if api.nvim_win_get_config(win).relative ~= "" then
      api.nvim_win_close(win, true)
    end
  end
  vim.cmd("silent! tabonly!")
  vim.cmd("silent! only!")
  vim.wo.previewwindow = false
  vim.cmd("enew!")
  vim.t.tab_buffers_excluded = nil
  local current = api.nvim_get_current_buf()
  for _, buf in ipairs(api.nvim_list_bufs()) do
    if buf ~= current then
      api.nvim_buf_delete(buf, { force = true })
    end
  end
  notices = {}
  drain()
end

