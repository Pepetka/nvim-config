test("external closure recovers unsaved files in a normal tab when only an excluded tab survives", function()
  local a = file()
  show(a)
  plugin.setup()
  local first = api.nvim_get_current_tabpage()
  vim.cmd("tabnew")
  local review = api.nvim_get_current_tabpage()
  vim.t[review].tab_buffers_excluded = true
  plugin.refresh()
  api.nvim_set_current_tabpage(first)
  vim.bo[a].modified = true
  vim.cmd("tabclose!")
  drain()
  local destination = api.nvim_get_current_tabpage()
  assert(destination ~= review)
  equal(api.nvim_tabpage_is_valid(review), true)
  equal(plugin.owners(a), { destination })
  equal(vim.bo[a].modified, true)
  equal(plugin.buffers(review), {})
end)

test("bootstrap from an excluded tab assigns hidden files to an ordinary tab", function()
  local hidden, visible, review_file = file(), file(), file()
  show(visible)
  local normal = api.nvim_get_current_tabpage()
  vim.cmd("tabnew")
  show(review_file)
  local review = api.nvim_get_current_tabpage()
